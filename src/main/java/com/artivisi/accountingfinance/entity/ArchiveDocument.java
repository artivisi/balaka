package com.artivisi.accountingfinance.entity;

import com.artivisi.accountingfinance.enums.ArchiveDocumentType;
import com.artivisi.accountingfinance.enums.ArchiveSource;
import com.artivisi.accountingfinance.enums.TextExtractionStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * A copy of a historical document (faktur, bupot, SPT, bank statement, ...) with its metadata (issue #51). The
 * original stays with its source; downloadedOn records when this copy was taken. The column search_vector is
 * generated by the database from the number, counterparty, description and extracted text and is not mapped.
 */
@Entity
@Table(name = "archive_documents")
@Getter
@Setter
public class ArchiveDocument extends TimestampedEntity {

    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "id_document", nullable = false, updatable = false)
    private Document document;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "id_import_batch", updatable = false)
    private ArchiveImportBatch importBatch;

    @Column(name = "doc_year", nullable = false)
    private Integer docYear;

    @Enumerated(EnumType.STRING)
    @Column(name = "doc_type", nullable = false, length = 30)
    private ArchiveDocumentType docType;

    @Enumerated(EnumType.STRING)
    @Column(name = "source", nullable = false, length = 20)
    private ArchiveSource source;

    @Column(name = "downloaded_on", nullable = false)
    private LocalDate downloadedOn;

    @Column(name = "doc_number", length = 100)
    private String docNumber;

    @Column(name = "counterparty", length = 255)
    private String counterparty;

    @Column(name = "amount", precision = 19, scale = 2)
    private BigDecimal amount;

    @Column(name = "description", columnDefinition = "TEXT")
    private String description;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "id_transaction")
    private Transaction transaction;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "id_journal_entry")
    private JournalEntry journalEntry;

    @Column(name = "extracted_text", columnDefinition = "TEXT")
    private String extractedText;

    @Enumerated(EnumType.STRING)
    @Column(name = "text_status", nullable = false, length = 20)
    private TextExtractionStatus textStatus;

    @Column(name = "created_by", nullable = false, length = 100, updatable = false)
    private String createdBy;
}
